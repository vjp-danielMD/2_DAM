    private void jButtonEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEliminarActionPerformed
        int filaSeleccionada = jTable1.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione una fila para eliminar");
            return;
        }
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        int idVideojuego = Integer.parseInt(modelo.getValueAt(filaSeleccionada, 0).toString());

        Connection con = null;
        PreparedStatement ps = null;
        try {
            con = Conexion.getConnection();
            ps = con.prepareStatement("DELETE FROM videojuegos WHERE idVideojuego = ?");
            ps.setInt(1, idVideojuego);
            ps.executeUpdate();

            cargarDatos();
        } catch (SQLException e) {
            e.printStackTrace();
        } finally {
            if (ps != null) try {
                ps.close();
            } catch (SQLException e) {
            }
            if (con != null) try {
                con.close();
            } catch (SQLException e) {
            }
        }
    }//GEN-LAST:event_jButtonEliminarActionPerformed

    private void jButtonPDFActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPDFActionPerformed
        try {
            URL url = getClass().getClassLoader().getResource("videojuegos.jrxml");
            File file = new File(url.toURI());
            JasperReport archivo = JasperCompileManager.compileReport(file.getAbsolutePath());
            Connection con = Conexion.getConnection();
            JasperPrint prin = JasperFillManager.fillReport(archivo, null, con);

            JasperExportManager.exportReportToPdfFile(prin, "reporte.pdf");

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButtonPDFActionPerformed

