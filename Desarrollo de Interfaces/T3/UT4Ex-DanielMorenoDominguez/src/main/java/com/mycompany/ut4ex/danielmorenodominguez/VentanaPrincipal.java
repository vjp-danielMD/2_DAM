    public void cargarDatos() {
        Connection con = null;
        Statement s = null;
        ResultSet rs = null;

        try {
            con = Conexion.getConnection();
            s = con.createStatement();
            rs = s.executeQuery("SELECT * FROM videojuegos");

            DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();

            modelo.setRowCount(0);

            while (rs.next()) {
                Videojuego v = new Videojuego(
                        rs.getInt("idVideojuego"),
                        rs.getString("nombre"),
                        rs.getString("plataforma"),
                        rs.getString("imagen")
                );
                modelo.addRow(v.toStringArray());
            }

        } catch (SQLException e) {
            e.printStackTrace();
        } finally {
            if (rs != null) try {
                rs.close();
            } catch (SQLException e) {
            }
            if (s != null) try {
                s.close();
            } catch (SQLException e) {
            }
            if (con != null) try {
                con.close();
            } catch (SQLException e) {
            }
        }
    }

