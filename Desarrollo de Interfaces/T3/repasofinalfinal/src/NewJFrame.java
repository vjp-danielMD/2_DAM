    private void jMenuItemOpenCanvasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItemOpenCanvasActionPerformed
        JFileChooser chooser = new JFileChooser();
        int resultado = chooser.showOpenDialog(this);

        if (resultado == JFileChooser.APPROVE_OPTION) {
            File archivo = chooser.getSelectedFile();
            try {
                BufferedImage img = ImageIO.read(archivo);
                bufferedImage = new BufferedImage(
                        jPanelLienzo.getWidth(),
                        jPanelLienzo.getHeight(),
                        BufferedImage.TYPE_INT_ARGB
                );

                g2d = bufferedImage.createGraphics();
                g2d.drawImage(img, 0, 0, jPanelLienzo.getWidth(), jPanelLienzo.getHeight(), null);

                jLabelLienzo.setIcon(new ImageIcon(bufferedImage));
                jLabelLienzo.repaint();

            } catch (IOException ex) {
                JOptionPane.showMessageDialog(this, "Error al abrir la imagen");
            }
        }
    }//GEN-LAST:event_jMenuItemOpenCanvasActionPerformed

