    private void jMenuItemClearCanvasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItemClearCanvasActionPerformed
        if (g2d != null && bufferedImage != null) {
            Graphics2D g2 = (Graphics2D) bufferedImage.getGraphics();
            g2.setColor(Color.WHITE);
            g2.fillRect(0, 0, bufferedImage.getWidth(), bufferedImage.getHeight());
            g2.dispose();
            jLabelLienzo.repaint();
        }
    }//GEN-LAST:event_jMenuItemClearCanvasActionPerformed

    private void jMenuItemOpenDocumentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItemOpenDocumentActionPerformed
        JFileChooser chooser = new JFileChooser();
        int resultado = chooser.showOpenDialog(null);
        if (resultado == JFileChooser.APPROVE_OPTION) {
            File archivo = chooser.getSelectedFile();
            try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
                jTextAreaDocument.setText("");
                String linea;
                while ((linea = br.readLine()) != null) {
                    jTextAreaDocument.append(linea + "\n");
                }
            } catch (IOException ex) {
                JOptionPane.showMessageDialog(null, "Error al abrir archivo");
            }
        }    }//GEN-LAST:event_jMenuItemOpenDocumentActionPerformed

    private void jMenuItemSaveDocumentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItemSaveDocumentActionPerformed
        JFileChooser chooser = new JFileChooser();
        int resultado = chooser.showSaveDialog(null);
        if (resultado == JFileChooser.APPROVE_OPTION) {
            File archivo = chooser.getSelectedFile();
            try (BufferedWriter bw = new BufferedWriter(new FileWriter(archivo))) {
                bw.write(jTextAreaDocument.getText());
                JOptionPane.showMessageDialog(null, "Documento guardado correctamente");
            } catch (IOException ex) {
                JOptionPane.showMessageDialog(null, "Error al guardar archivo");
            }
        }    }//GEN-LAST:event_jMenuItemSaveDocumentActionPerformed

